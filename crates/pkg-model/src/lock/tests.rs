use super::*;

/// A digest of the tests, of `byte` repeated.
fn digest(byte: char) -> String {
    format!("sha256:{}", byte.to_string().repeat(64))
}

/// A lockfile of a plugin of the registry, one that it needs, one of git,
/// and one that `sleip dev` links.
fn example() -> String {
    format!(
        r#"# Generated by sleip. Do not edit by hand.
version = 1
api = "0.1.3"

[[package]]
name = "sephiroth74/search-plus"
version = "0.1.2"
kind = "luau"
source = "registry+https://pkg.lokyr.dev"
checksum = "{}"
capabilities = ["terminal-read", "clipboard-write", "net:api.github.com"]
dependencies = ["lokyr/themes 0.3.1"]

[[package]]
name = "lokyr/themes"
version = "0.3.1"
kind = "themes"
source = "registry+https://pkg.lokyr.dev"
checksum = "{}"

[[package]]
name = "acme/git-status"
version = "0.2.0"
kind = "luau"
source = "git+https://github.com/acme/git-status#{}"
checksum = "{}"
capabilities = ["process-read"]

[[package]]
name = "me/my-plugin"
version = "0.0.1"
kind = "luau"
source = "dev+/Users/me/dev/my-plugin"
"#,
        digest('a'),
        digest('b'),
        "c".repeat(40),
        digest('d'),
    )
}

#[test]
fn the_lockfile_reads_each_plugin_and_writes_back_the_same_whole() {
    let lock = Lock::parse(&example()).unwrap();
    assert_eq!(lock.api, "0.1.3");
    assert_eq!(lock.packages.len(), 4);
    let search = &lock.packages["sephiroth74/search-plus"];
    assert_eq!(search.version, "0.1.2");
    assert_eq!(search.kind, Kind::Luau);
    assert_eq!(
        search.source,
        Source::Registry("https://pkg.lokyr.dev".to_owned())
    );
    assert_eq!(
        search.checksum.map(|checksum| checksum.to_string()),
        Some(digest('a'))
    );
    assert_eq!(
        search.capabilities,
        [
            Capability::TerminalRead,
            Capability::ClipboardWrite,
            Capability::Net("api.github.com".to_owned())
        ]
    );
    assert_eq!(search.dependencies["lokyr/themes"], "0.3.1");
    assert_eq!(
        lock.packages["acme/git-status"].source,
        Source::Git {
            url: "https://github.com/acme/git-status".to_owned(),
            commit: "c".repeat(40),
        }
    );
    let dev = &lock.packages["me/my-plugin"];
    assert_eq!(
        dev.source,
        Source::Dev("/Users/me/dev/my-plugin".to_owned())
    );
    assert_eq!(dev.checksum, None);
    // Written back: its header, its plugins in their names' order, the
    // same once read.
    let text = lock.text();
    assert!(text.starts_with(HEADER), "{text}");
    assert_eq!(Lock::parse(&text).unwrap(), lock, "{text}");
    let names: Vec<&str> = text
        .lines()
        .filter_map(|line| line.strip_prefix("name = "))
        .collect();
    assert_eq!(
        names,
        [
            "\"acme/git-status\"",
            "\"lokyr/themes\"",
            "\"me/my-plugin\"",
            "\"sephiroth74/search-plus\""
        ]
    );
    // A lockfile of no plugin.
    let empty = Lock::parse("version = 1\napi = \"0.1.0\"\n").unwrap();
    assert!(empty.packages.is_empty());
    assert_eq!(Lock::parse(&empty.text()).unwrap(), empty);
}

#[test]
fn a_wrong_lockfile_is_refused_at_its_place() {
    let base = example();
    let wrong = |from: &str, to: &str| {
        assert!(base.contains(from), "{from}");
        Lock::parse(&base.replacen(from, to, 1))
            .unwrap_err()
            .to_string()
    };
    for (from, to, told) in [
        (
            "version = 1",
            "version = 2",
            "2:11: a lockfile of the version 2",
        ),
        (
            "api = \"0.1.3\"",
            "api = \"0.1\"",
            "3:7: `0.1` is not a version",
        ),
        (
            "name = \"lokyr/themes\"",
            "name = \"sephiroth74/search-plus\"",
            "15:8: `sephiroth74/search-plus` is locked twice",
        ),
        (
            "name = \"sephiroth74/search-plus\"",
            "name = \"Search\"",
            "6:8: `Search` is not a plugin's name",
        ),
        (
            "version = \"0.1.2\"",
            "version = \"0.1\"",
            "7:11: `0.1` is not a version",
        ),
        (
            "kind = \"themes\"",
            "kind = \"builtin\"",
            "17:8: a built-in plugin is linked in the app",
        ),
        (
            "source = \"dev+/Users/me/dev/my-plugin\"",
            "source = \"dev+dev/my-plugin\"",
            "33:10: `dev+dev/my-plugin` is not a source",
        ),
        (
            "#cccc",
            "#ccc",
            "25:10: `git+https://github.com/acme/git-status#",
        ),
        (
            "source = \"registry+https://pkg.lokyr.dev\"",
            "source = \"ftp+x\"",
            "9:10: `ftp+x` is not a source",
        ),
        (
            "source = \"dev+/Users/me/dev/my-plugin\"",
            "source = \"dev+/Users/me/dev/my-plugin\"\nchecksum = \"sha256:x\"",
            "34:12: a folder that `sleip dev` links has no checksum",
        ),
        (
            "\"terminal-read\"",
            "\"terminal-reads\"",
            "11:17: `terminal-reads` is no capability",
        ),
        (
            "\"net:api.github.com\"",
            "\"net:\"",
            "11:53: `net:` is no capability",
        ),
        (
            "[\"lokyr/themes 0.3.1\"]",
            "[\"lokyr/themes\"]",
            "12:17: `lokyr/themes` is not a plugin needed",
        ),
        (
            "[\"lokyr/themes 0.3.1\"]",
            "[\"lokyr/themes 0.3.2\"]",
            "6:8: `sephiroth74/search-plus` needs `lokyr/themes 0.3.2`, which the lockfile does not hold",
        ),
        (
            "version = 1",
            "version = 1\nother = 2",
            "unknown field `other`",
        ),
    ] {
        let told_back = wrong(from, to);
        assert!(told_back.contains(told), "{from} → {to}: {told_back}");
    }
    // A plugin of the store of no checksum, and a checksum that is not one.
    let missing = base.replacen(&format!("checksum = \"{}\"\n", digest('b')), "", 1);
    assert!(
        Lock::parse(&missing)
            .unwrap_err()
            .to_string()
            .contains("`lokyr/themes` has no checksum")
    );
    let short = base.replacen(&digest('b'), "sha256:bbb", 1);
    assert!(
        Lock::parse(&short)
            .unwrap_err()
            .to_string()
            .contains("is not `sha256:` and 64 hexadecimal digits")
    );
}

#[test]
fn the_lockfile_is_written_whole_and_read_back_of_its_file() {
    let folder = std::env::temp_dir().join(format!("lokyr-lock-{}", std::process::id()));
    std::fs::create_dir_all(&folder).unwrap();
    let path = folder.join(FILE);
    assert_eq!(Lock::read(&path).unwrap(), None);
    let lock = Lock::parse(&example()).unwrap();
    lock.write(&path).unwrap();
    assert_eq!(Lock::read(&path).unwrap().as_ref(), Some(&lock));
    let mut fewer = lock.clone();
    fewer.packages.remove("me/my-plugin");
    fewer.write(&path).unwrap();
    assert_eq!(Lock::read(&path).unwrap(), Some(fewer));
    // No file of the write left beside it.
    let left: Vec<_> = std::fs::read_dir(&folder).unwrap().collect();
    assert_eq!(left.len(), 1);
    std::fs::write(&path, "version = 3\napi = \"0.1.0\"\n").unwrap();
    let error = Lock::read(&path).unwrap_err();
    assert_eq!(error.at, Some((1, 11)));
    assert!(
        error.message.starts_with(&path.display().to_string()),
        "{error}"
    );
    let _ = std::fs::remove_dir_all(&folder);
}
